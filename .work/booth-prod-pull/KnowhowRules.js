/** 金額・予算表現を含む文または行を返す純関数。寸法・日付・インチは対象外。 */
function Knowhow_findBudgetMentions(text) {
  var source = String(text == null ? '' : text);
  var chunks = source.split(/(?<=[。！？!?])|\r?\n/).map(function (s) { return s.trim(); }).filter(Boolean);
  var money = /(?:[¥￥]\s*\d[\d,]*(?:\.\d+)?|(?:税込|税抜)?\s*\d[\d,]*(?:\.\d+)?\s*(?:億|万|千)(?:円)?|\d[\d,]*(?:\.\d+)?\s*円)/;
  var budgetWithNumber = /(?:ご?予算|予算(?:額|感)?)[^。！？\n]{0,30}\d[\d,]*(?:\.\d+)?\s*(?:億|万|千)?(?:円)?/;
  return chunks.filter(function (s) { return money.test(s) || budgetWithNumber.test(s); });
}

/** 対外・デザイナー文書から予算文を除外し、確認事項へ移す。 */
function Knowhow_stripBudgetMentions(text) {
  var mentions = Knowhow_findBudgetMentions(text);
  if (!mentions.length) return { text: String(text || ''), mentions: [] };
  var cleaned = String(text || '');
  mentions.forEach(function (mention) { cleaned = cleaned.replace(mention, ''); });
  cleaned = cleaned.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
  return { text: cleaned, mentions: mentions };
}

