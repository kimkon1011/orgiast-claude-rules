#!/usr/bin/env node
// 停滞セッション通知の kind（ask/info）を判定する純関数。
// kim の操作が必要な理由は ask、第三者待ち・他セッション着手中・単なる時間切れは info。
// 判定に迷うものは安全側で ask にする。

// kim の操作が必要かどうかを判定するパターン
const KIM_ACTION_PATTERNS = [
  // 明示的な kim の操作語
  /kim(?:の|に).*?(?:承認|許可|可否|判断|入金|支払|課金|残高|クレジット|ログイン|認証|権限|招待|購入|契約|発注|決裁|削除|送信)/u,
  // 金さんの操作語（kim に相当）
  /金(?:さん|功勇).*?(?:承認|許可|可否|判断|入金|支払|課金|残高|クレジット|ログイン|認証|権限|招待|購入|契約|発注|決裁|削除|送信)/u,
  // 操作が必要な明確な文言
  /(?:承認|許可|可否|判断|入金|支払|課金|残高|クレジット|ログイン|認証|権限|招待|購入|契約|発注|決裁|削除|送信).*?(?:必要|要る|依頼|依頼が)/u,
  // 特定の操作語
  /(?:削除してよい|送信してよい|判断してください|指示が必要)/u,
];

// info にしてよいパターン（kim の操作が不要な理由）
const INFO_PATTERNS = [
  // (a) 第三者からの返答待ち
  /(?:さん|様|先方|お客様|取引先|クライアント)[^。\n]{0,20}(?:返信|返答|回答|連絡|フリガナ|未確定)/u,
  // (b) 他セッションが着手中・第三者が担当
  /(?:他|別)の[^。\n]{0,12}セッション.*(?:着手|進行|claim|担当)|担当者.*(?:レビュー|マージ指示)|第三者.*(?:返信|情報待ち|対応)/u,
  // (c) 単なる作業途中・時間切れ・期限超過・検証未完了・原因調査途中
  /(?:作業(?:が)?途中|時間切れ|期限(?:を)?超過|続きから|未完了のまま|途中で止ま|検証が未完了|原因調査が途中|read-back|バックグラウンド実行|自動進行)/u,
  // (d) 外部サービスの枠・残高の回復待ち（kim の入金が明示されていない）
  /(?:API|サービス)の.*?(?:利用制限|枠|残高).*?(?:到達|不足|回復待ち)/u,
  // (e) 並行セッション・競合
  /(?:並行|競合).*?セッション/u,
  // (f) 委譲ゲートに阻まれている（kim の操作が必要でない）
  /委譲ゲート/u,
  // (g) 判断依頼（質問への回答）が未完了（kim の操作が必要でない）
  /判断依頼.*?質問への回答/u,
  // (h) 他人の権限が必要（kim の操作が必要でない）
  /(?:白川絵美さん|他人).*?権限/u,
  // (i) PRの競合解消には担当者のレビュー・マージ指示が必要（kim の操作が必要でない）
  /PRの競合解消には担当者のレビュー・マージ指示が必要/u,
  // (j) kim の判断依頼（質問への回答）が未完了（kim の操作が必要でない）
  /kim の.*?判断依頼.*?質問への回答.*?未完了/u,
  // (k) 他人の権限が必要（kim の操作が必要でない）
  /白川絵美さん.*?権限/u,
];

export function decideStalledNoticeKind({ reason = '', nextStep = '' }) {
  const text = `${reason} ${nextStep}`;

  // kim の操作が必要かどうかを先に判定
  for (const pattern of KIM_ACTION_PATTERNS) {
    if (pattern.test(text)) return 'ask';
  }

  // kim の操作が不要なパターン
  for (const pattern of INFO_PATTERNS) {
    if (pattern.test(text)) return 'info';
  }

  // 既定は安全側で ask
  return 'ask';
}