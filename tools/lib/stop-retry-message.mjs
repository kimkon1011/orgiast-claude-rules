export const STOP_RETRY_INSTRUCTION = '前のメッセージの経緯・ログ・説明は繰り返さない。指摘分を直したうえで、この書き直しが kim の読む最後のメッセージになる前提で書く: 末尾3行の直前に【最終まとめ】を置き、①報告（結論・結果・検証）②kim の確認事項（文面・選択肢・URL は全文）③kim がやること をすべて載せ、前のメッセージを参照させない（「上記」「前述」禁止）。書き直す前に、このターン中に届いた kim の新着メッセージを確かめ、もう答えが来た質問は②から外して答えを反映する。前のメッセージと同じ質問を出し直すときは、質問の先頭に「（前のメッセージと同じ質問です。もう答えていれば不要です）」と書き、新しい質問に見せない。';

export function withStopRetryInstruction(reason) {
  return `${STOP_RETRY_INSTRUCTION}\n\n${reason}`;
}
